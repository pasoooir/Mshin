import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

await mkdir("artifacts", { recursive: true });

const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
  await page.waitForFunction(() => window.MshinAssets?.ready === true, undefined, { timeout: 15000 });
  const preloadState = await page.evaluate(() => ({ worlds: window.MshinAssets.worlds.filter(Boolean).length, cars: Object.values(window.MshinAssets.cars).filter(Boolean).length, failures: window.MshinAssets.failures.length, menuArt: getComputedStyle(document.querySelector("#home .panel"), "::before").backgroundImage }));
  assert.equal(preloadState.worlds, 10, "all ten world SVGs should be decoded before the menu is interactive");
  assert.equal(preloadState.cars, 5, "all five vehicle SVGs should be decoded before the menu is interactive");
  assert.equal(preloadState.failures, 0, "the local vector asset pack should load without CDN/network dependencies");
  assert.match(preloadState.menuArt, /world-01[.]svg/, "the home screen should use themed visual art");
  await page.locator("#play").click();
  assert.equal(await page.locator(".world").count(), 10, "all 10 worlds should be selectable");
  assert.equal(await page.locator(".carChoice").count(), 5, "garage should offer three starter and two unlockable cars");
  await page.getByRole("button", { name: /Comet GT/ }).click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("mshin-settings-v1")).carId), "comet", "selected car should persist");
  await page.reload({ waitUntil: "networkidle" });
  await page.locator("#play").click();
  assert.match(await page.locator(".carChoice.active").textContent(), /Comet GT/, "garage should restore the saved car");
  await page.getByRole("button", { name: /Neon City/ }).click();
  assert.equal(await page.locator(".stage").count(), 5, "each world should expose five stages");
  await page.getByRole("button", { name: /STAGE 05.*Neon Finale/ }).click();
  const raceRequests = [];
  page.on("request", request => { if (request.isNavigationRequest() || request.resourceType() !== "other") raceRequests.push(request.url()); });
  await page.locator("#startRace").click();
  const requestCountAtStart = raceRequests.length;
  await page.waitForTimeout(1100);
  assert.equal(raceRequests.length, requestCountAtStart, "starting a race must not trigger late asset/network requests");
  const frameMetrics = await page.evaluate(() => window.MshinPerformance);
  assert.ok(frameMetrics.samples >= 30, "race loop should publish rolling frame-time samples");
  assert.ok(Number.isFinite(frameMetrics.avgFrameMs) && frameMetrics.avgFrameMs < 50, "average game JS frame work should stay below 50ms");
  assert.ok(Number.isFinite(frameMetrics.p95FrameMs) && frameMetrics.p95FrameMs < 100, "95th percentile game JS frame work should stay below 100ms");
  assert.ok(Number.isFinite(frameMetrics.maxFrameMs) && frameMetrics.maxFrameMs < 200, "no single game JS frame should exceed 200ms in smoke run");
  assert.equal(frameMetrics.trackCacheBuilds, 1, "static track and world art should be rasterized once per selected stage, not on every frame");
  assert.equal(await page.locator("#soundToggle").getAttribute("aria-pressed"), "true", "sound should start enabled");
  await page.locator("#soundToggle").click();
  assert.equal(await page.locator("#soundToggle").getAttribute("aria-pressed"), "false", "sound toggle should mute audio");
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem("mshin-settings-v1")).sound), false, "mute preference should persist");
  await page.reload({ waitUntil: "networkidle" });
  await page.locator("#play").click();
  await page.getByRole("button", { name: /Neon City/ }).click();
  await page.getByRole("button", { name: /STAGE 05.*Neon Finale/ }).click();
  await page.locator("#startRace").click();
  assert.equal(await page.locator("#soundToggle").getAttribute("aria-pressed"), "false", "saved mute preference should survive reload");
  await page.locator("#soundToggle").click();
  assert.equal(await page.locator("#soundToggle").getAttribute("aria-pressed"), "true", "sound toggle should restore audio");
  assert.equal(await page.locator("#hud").isVisible(), true, "race HUD should become visible");
  assert.match(await page.locator("#position").textContent(), /^[1-4] \/ 4$/, "live race position should show the player among three AI rivals");
  assert.match(await page.locator("#stageName").textContent(), /WORLD 05.*STAGE 05/);
  await page.keyboard.down("ArrowUp");
  await page.waitForTimeout(2400);
  await page.keyboard.up("ArrowUp");
  assert.ok(Number(await page.locator("#speed").textContent()) > 0, "accelerator should increase speed");
  await page.waitForFunction(() => parseFloat(document.querySelector("#nitroFill").style.width) > 25, undefined, { timeout: 6000 });
  const chargedNitro = parseFloat(await page.locator("#nitroFill").evaluate(el => el.style.width));
  assert.ok(chargedNitro >= 50, "collecting a track pickup should recharge nitro");
  await page.locator("#nitro").click();
  await page.waitForTimeout(180);
  await page.waitForFunction(() => parseFloat(document.querySelector("#nitroFill").style.width) < 50, undefined, { timeout: 3000 });
  assert.ok(parseFloat(await page.locator("#nitroFill").evaluate(el => el.style.width)) < chargedNitro, "nitro boost should consume stored charge");
  const canvasState = await page.locator("#game").evaluate(canvas => {
    const context = canvas.getContext("2d");
    const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
    let visible = 0;
    for (let i = 3; i < pixels.length; i += 4 * 32) if (pixels[i] > 0) visible++;
    return { width: canvas.width, height: canvas.height, visiblePixels: visible, imageBytes: canvas.toDataURL("image/png").length };
  });
  assert.ok(canvasState.width > 0 && canvasState.height > 0, "game canvas should have a real drawing surface");
  assert.ok(canvasState.visiblePixels > 100, "game canvas should contain visible rendered pixels");
  assert.ok(canvasState.imageBytes > 1000, "gameplay frame should not be a blank image");
  await page.screenshot({ path: "artifacts/mshin-gameplay-desktop.png" });
  await page.locator("#pause").click();
  assert.equal(await page.locator("#pausePanel").isVisible(), true, "pause panel should open");
  await page.locator("#resume").click();
  assert.equal(await page.locator("#pausePanel").isVisible(), false, "resume should close pause panel");
  await page.locator("#pause").click();
  await page.locator("#quitRace").click();
  assert.equal(await page.locator("#select").isVisible(), true, "exit should return to stage selection");
  assert.deepEqual(errors, [], "page should not throw runtime exceptions");
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  mobile.on("pageerror", error => errors.push(error.message));
  await mobile.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
  await mobile.locator("#play").click();
  await mobile.locator("#startRace").click();
  assert.equal(await mobile.locator("#hud").isVisible(), true, "mobile race HUD should render");
  assert.ok((await mobile.locator("#stick").boundingBox()).width >= 90, "mobile joystick should remain touch-sized");
  assert.ok((await mobile.locator("#gas").boundingBox()).width >= 60, "mobile gas pedal should remain touch-sized");
  assert.ok((await mobile.locator("#nitro").boundingBox()).width >= 60, "mobile nitro control should remain touch-sized");
  assert.ok(await mobile.locator(".stats").evaluate(el => el.getBoundingClientRect().right <= document.querySelector("#soundToggle").getBoundingClientRect().left), "compact mobile race stats should not overlap sound controls");
  assert.ok(await mobile.locator("#pause").evaluate(el => el.getBoundingClientRect().right <= innerWidth), "mobile pause control should remain inside the viewport");
  await mobile.screenshot({ path: "artifacts/mshin-gameplay-mobile.png" });
  assert.deepEqual(errors, [], "desktop and mobile pages should not throw runtime exceptions");
  const economy = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  await economy.addInitScript(() => { if (!localStorage.getItem("mshin-progress-v1")) localStorage.setItem("mshin-progress-v1", JSON.stringify({ completed: [], best: {}, credits: 1000 })); });
  economy.on("pageerror", error => errors.push(error.message));
  await economy.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
  await economy.locator("#play").click();
  assert.equal(await economy.locator(".carChoice").count(), 5, "garage should show three starter and two unlockable cars");
  assert.equal((await economy.locator("#credits").textContent()).trim(), "1000 🪙", "wallet should load saved coins");
  assert.match(await economy.locator("#weatherInfo").textContent(), /CLEAR/, "Green Valley should use clear weather");
  await economy.getByRole("button", { name: /Desert Storm/ }).click();
  assert.match(await economy.locator("#weatherInfo").textContent(), /SAND/, "Desert Storm should select sand weather");
  await economy.getByRole("button", { name: /Thunder EV/ }).click();
  assert.equal(await economy.getByRole("button", { name: /Thunder EV/ }).getAttribute("class").then(v => v.includes("locked")), false, "purchased car should unlock");
  assert.match(await economy.locator(".carChoice.active").textContent(), /Thunder EV/, "newly unlocked car should be selected immediately");
  await economy.getByRole("button", { name: /Upgrade · 180/ }).nth(0).click();
  assert.match(await economy.locator("#upgrades").textContent(), /Engine power · Lv 1\/3/, "engine upgrade should advance its level");
  await economy.getByRole("button", { name: /Upgrade · 180/ }).nth(0).click();
  await economy.getByRole("button", { name: /Upgrade · 180/ }).nth(0).click();
  assert.equal((await economy.locator("#credits").textContent()).trim(), "10 🪙", "unlocking and three upgrades should deduct exact coin costs");
  await economy.reload({ waitUntil: "networkidle" });
  await economy.locator("#play").click();
  assert.match(await economy.locator(".carChoice.active").textContent(), /Thunder EV/, "unlocked selected car should persist after reload");
  assert.match(await economy.locator("#upgrades").textContent(), /Engine power · Lv 1\/3/, "car upgrades should persist after reload");
  await economy.getByRole("button", { name: /Desert Storm/ }).click();
  await economy.locator("#startRace").click();
  await economy.keyboard.down("ArrowUp");
  await economy.waitForFunction(() => !document.querySelector("#finish").classList.contains("hidden"), undefined, { timeout: 45000 });
  await economy.keyboard.up("ArrowUp");
  assert.match(await economy.locator("#finishText").textContent(), /You earned \d+ coins!/, "finishing a stage should award coins");
  assert.ok(await economy.evaluate(() => JSON.parse(localStorage.getItem("mshin-progress-v1")).credits > 10), "race rewards should persist in the wallet");
  assert.ok(await economy.evaluate(() => JSON.parse(localStorage.getItem("mshin-progress-v1")).achievements.includes("first-finish")), "first race should unlock the First Finish achievement");
  assert.equal(await economy.locator(".achievement.earned").filter({ hasText: "First Finish" }).count(), 1, "achievement board should show the earned badge");
  assert.match(await economy.locator("#finishText").textContent(), /First Finish/, "finish screen should announce milestone bonus");
  assert.deepEqual(errors, [], "economy, achievements and weather flows should not throw runtime exceptions");
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null, { timeout: 5000 });
  await page.context().setOffline(true);
  await page.reload({ waitUntil: "domcontentloaded" });
  assert.equal(await page.locator("#home").isVisible(), true, "game shell should load while offline after first visit");
  await page.locator("#play").click();
  assert.equal(await page.locator(".world").count(), 10, "cached game should remain playable offline");
  await page.context().setOffline(false);
  process.stdout.write("Browser smoke passed: five-car garage, coin unlocks, three persistent upgrades, race rewards, milestone achievements, weather profiles, nitro, saved audio, 10 worlds, 50 stages, desktop/mobile screenshots, offline PWA launch, pause/resume, and touch controls.\\n");
} finally {
  await browser.close();
}
